/**
 * Returns the plain-language definition of a term, or undefined if not found.
 */
export function getDefinition(termKey: string): string | undefined {
  const normalized = termKey.toLowerCase().trim();
  return GLOSSARY[normalized]?.definition;
}

/**
 * Wraps known aerospace terms with an accessible explain-tag and tooltip.
 */
export function wrapGlossaryTerms(text: string): string {
  let result = text;
  for (const [key, termObj] of Object.entries(GLOSSARY)) {
    const regex = new RegExp(`\\b(${key})\\b`, 'gi');
    result = result.replace(regex, `<span class="glossary-term" tabindex="0" data-term="${key}" title="${termObj.definition}">$1<span class="glossary-tip" role="tooltip">${termObj.definition}</span></span>`);
  }
  return result;
}

